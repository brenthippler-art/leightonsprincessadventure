import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

/**
 * OFFLINE SUPPORT: after `npm run build`, this little plugin writes dist/sw.js, a "service worker".
 * It lists every file of the finished game; the browser saves them all on the first visit,
 * so the game then works with no internet at all (car trips!).
 * The cache name includes a fingerprint of the files, so a new version replaces the old one cleanly.
 */
function offlineServiceWorker(): Plugin {
  return {
    name: 'offline-service-worker',
    apply: 'build',
    closeBundle() {
      const dist = 'dist';
      const files: string[] = [];
      const walk = (dir: string) => {
        for (const name of readdirSync(dir)) {
          const full = join(dir, name);
          if (statSync(full).isDirectory()) walk(full);
          else if (name !== 'sw.js') files.push(relative(dist, full).split('\\').join('/'));
        }
      };
      walk(dist);
      const hash = createHash('sha256');
      for (const f of files.sort()) hash.update(f).update(readFileSync(join(dist, f)));
      const version = hash.digest('hex').slice(0, 12);
      const urls = ['./', ...files.map((f) => `./${f}`)];
      writeFileSync(
        join(dist, 'sw.js'),
        `// Generated by vite.config.ts at build time. Caches the whole game for offline play.
const CACHE = 'leighton-${version}';
const FILES = ${JSON.stringify(urls, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Serve from the saved copy first; only ask the server for something not saved yet.
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      if (req.mode === 'navigate') return caches.match('./index.html').then((page) => page || fetch(req));
      return fetch(req);
    }),
  );
});
`,
      );
      console.log(`offline service worker: ${urls.length} files cached as ${version}`);
    },
  };
}

// Relative base so the built game works from any folder (or straight off a USB stick / local server).
export default defineConfig({
  base: './',
  server: { port: 5173 },
  build: {
    target: 'es2022',
    chunkSizeWarningLimit: 2000, // Phaser itself is ~1.2 MB; that's expected.
  },
  plugins: [offlineServiceWorker()],
});
